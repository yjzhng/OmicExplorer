// Regenerate src/main/degEssential.ts from DEG (Database of Essential Genes, tubic.org/deg).
//
// DEG is essential-only: every gene it lists is an experimentally-determined essential gene. We
// download all annotation tables, keep just the UniProt/Swiss-Prot accession column, dedupe, and
// emit the set of essential accessions. Organism/strain, method, sequences, GO, COG etc. are all
// discarded — the app maps a gene to "essential" purely by UniProt accession membership.
//
// DEG has no API and was last updated 2020, so this is a one-off vendored snapshot. Re-run with:
//   node scripts/build-deg-essential.mjs
//
// Coverage note: the archaea (deg_annotation_a, ~960 genes) and non-coding tables carry no UniProt
// accessions (GI + RefSeq only), so those essential genes are not represented here. Human genes in
// deg_annotation_e that only carry an HGNC id (no UniProt) are likewise dropped — by design, since
// the join key is UniProt.
import { writeFileSync, mkdtempSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { tmpdir } from 'node:os'
import { execFileSync } from 'node:child_process'

const BASE = 'https://tubic.org/deg/public/download'
// Annotation tables that carry a UniProt column (prokaryote proteins + eukaryotes).
const FILES = ['deg_annotation_p', 'deg_annotation_e']
// Swiss-Prot / TrEMBL accession (6- or 10-char forms).
const ACC = /^(?:[OPQ][0-9][A-Z0-9]{3}[0-9]|[A-NR-Z][0-9](?:[A-Z][A-Z0-9]{2}[0-9]){1,2})$/

const tmp = mkdtempSync(join(tmpdir(), 'deg-'))
// DEG's annotation zips use streaming (data-descriptor) headers, so decode via system `unzip -p`.
async function fetchCsvFromZip(url) {
  const zip = join(tmp, 'a.zip')
  writeFileSync(zip, Buffer.from(await (await fetch(url)).arrayBuffer()))
  return execFileSync('unzip', ['-p', zip], { maxBuffer: 1 << 28 }).toString('latin1')
}

const essential = new Set()
for (const f of FILES) {
  const csv = await fetchCsvFromZip(`${BASE}/${f}.csv.zip`)
  let n = 0
  for (const line of csv.split(/\r?\n/)) {
    for (const cell of line.split(';')) {
      const c = cell.replace(/"/g, '').trim()
      for (const tok of c.split(/[\s,;|]+/)) if (ACC.test(tok)) (essential.add(tok), n++)
    }
  }
  console.log(`${f}: +${n} accession hits`)
}

const list = [...essential].sort()
console.log(`total unique essential UniProt accessions: ${list.length}`)

const out = `/**
 * Essential-gene UniProt accessions from DEG (Database of Essential Genes, tubic.org/deg).
 * GENERATED by scripts/build-deg-essential.mjs — do not edit by hand.
 *
 * DEG is essential-only, so membership here means "experimentally essential in at least one DEG
 * organism". A gene is marked essential purely by UniProt-accession membership; organism/strain and
 * condition are intentionally discarded (see the generator for coverage caveats).
 */
let set: Set<string> | null = null
/** True if \`acc\` (a bare UniProt accession, no isoform suffix) is an essential gene in DEG. */
export function isEssentialAccession(acc: string): boolean {
  if (!set) set = new Set(DEG_ESSENTIAL_ACCESSIONS.split('\\n'))
  return set.has(acc)
}
/** Newline-joined, sorted list of ${list.length} accessions (deduped snapshot). */
const DEG_ESSENTIAL_ACCESSIONS =
  '${list.join('\\n')}'
`

const dst = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'main', 'degEssential.ts')
writeFileSync(dst, out)
rmSync(tmp, { recursive: true, force: true })
console.log(`wrote ${dst}`)
