// Regenerate src/main/cegEssential.ts from the Hart lab's core-essential (CEGv2) and
// non-essential (NEGv1) gold-standard gene sets.
//
// Unlike DEG — a union of screens across many organisms, where membership means "essential
// somewhere" — these are curated HUMAN reference sets, and NEGv1 gives something DEG has none of:
// genes positively known NOT to be essential. That turns the app's Essential / NA split into a real
// Essential / Non-essential / Unknown one.
//
// The sets ship as HGNC symbols; the app joins on UniProt accession, so symbols are resolved here
// (against human reviewed UniProtKB, primary names and synonyms) and the accessions are vendored.
// Re-run with:
//   node scripts/build-ceg-essential.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const SRC = {
  essential: 'https://raw.githubusercontent.com/hart-lab/bagel/master/CEGv2.txt',
  nonEssential: 'https://raw.githubusercontent.com/hart-lab/bagel/master/NEGv1.txt'
}
const T = (u) => fetch(u, { signal: AbortSignal.timeout(180000) })

// symbol (upper) → accessions, from human reviewed UniProtKB. Synonyms are included because the
// gold-standard sets predate several HGNC renames.
const res = await T(
  'https://rest.uniprot.org/uniprotkb/stream?query=' +
    encodeURIComponent('organism_id:9606 AND reviewed:true') +
    '&fields=accession,gene_names&format=tsv'
)
if (!res.ok) throw new Error(`UniProt HTTP ${res.status}`)
const bySym = new Map()
const uniLines = (await res.text()).replace(/\r/g, '').split('\n').filter(Boolean)
for (const line of uniLines.slice(1)) {
  const [acc, names = ''] = line.split('\t')
  for (const s of names.trim().split(/\s+/)) {
    if (!s) continue
    const k = s.toUpperCase()
    if (!bySym.has(k)) bySym.set(k, [])
    bySym.get(k).push(acc)
  }
}
console.log(
  `UniProt: ${uniLines.length - 1} human reviewed entries, ${bySym.size} symbols/synonyms`
)

const sets = {}
for (const [cls, url] of Object.entries(SRC)) {
  const rows = (await (await T(url)).text()).replace(/\r/g, '').split('\n').filter(Boolean).slice(1)
  const symbols = rows.map((l) => l.split('\t')[0].trim()).filter(Boolean)
  const accs = new Set()
  const missed = []
  for (const s of symbols) {
    const hit = bySym.get(s.toUpperCase())
    if (hit) hit.forEach((a) => accs.add(a))
    else missed.push(s)
  }
  sets[cls] = accs
  console.log(
    `${cls}: ${symbols.length} symbols → ${accs.size} accessions` +
      `, ${missed.length} unmapped${missed.length ? ` (${missed.join(' ')})` : ''}`
  )
}

// A shared synonym can land one accession in both sets; it can't be both, so drop it from each
// rather than let an arbitrary order decide.
const both = [...sets.essential].filter((a) => sets.nonEssential.has(a))
for (const a of both) {
  sets.essential.delete(a)
  sets.nonEssential.delete(a)
}
console.log(
  `dropped ${both.length} ambiguous accession(s)${both.length ? `: ${both.join(' ')}` : ''}`
)

const list = (s) => [...s].sort()
const ess = list(sets.essential)
const non = list(sets.nonEssential)
const out = `/**
 * Core-essential (CEGv2) and non-essential (NEGv1) human gene sets from the Hart lab, resolved to
 * UniProt accessions. GENERATED by scripts/build-ceg-essential.mjs — do not edit by hand.
 *
 * These are curated HUMAN reference sets, not a screen union: CEGv2 is the core-essential
 * gold standard (fundamental cellular machinery), NEGv1 the matched non-essential one. Unlike DEG
 * this carries real negatives, so a gene can be reported non-essential rather than merely unknown.
 *
 * Human only, and deliberately not extended to other species by symbol: orthologs of core
 * essentials usually ARE essential, but that's an inference the data doesn't make.
 */
let sets: { ess: Set<string>; non: Set<string> } | null = null
/** 'essential' / 'non-essential' for \`acc\` (a bare UniProt accession), or '' if it's in neither
 *  set — which means untested here, NOT non-essential. */
export function cegClass(acc: string): 'essential' | 'non-essential' | '' {
  if (!sets)
    sets = { ess: new Set(CEG_ESSENTIAL.split('\\n')), non: new Set(NEG_NON_ESSENTIAL.split('\\n')) }
  if (sets.ess.has(acc)) return 'essential'
  if (sets.non.has(acc)) return 'non-essential'
  return ''
}
/** Newline-joined, sorted CEGv2 accessions (${ess.length}). */
const CEG_ESSENTIAL =
  '${ess.join('\\n')}'
/** Newline-joined, sorted NEGv1 accessions (${non.length}). */
const NEG_NON_ESSENTIAL =
  '${non.join('\\n')}'
`
const dst = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'main', 'cegEssential.ts')
writeFileSync(dst, out)
console.log(`wrote ${dst} (${ess.length} essential, ${non.length} non-essential)`)
